"""Package actual compiled images with verified MCP hardware; never flash a device."""
import hashlib,json,os,shutil,subprocess,sys,zipfile
from pathlib import Path
R=Path(__file__).resolve().parents[1];W=R.parents[1]/'work/interface-redesign'
sys.path.insert(0,str(R/'src'))
from pcb_mcp import parts
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
report=json.loads((W/'report.json').read_text());hardware=json.loads((R/'firmware/am2302/hardware.json').read_text())
assert report['passed'] and report['original_projects_unchanged']
assert hardware['project_id']==report['project_id'] and hardware['pcb_build_id']==report['pcb_build_id']
assert hardware['source_evidence_hash']==report['source_evidence_hash']==parts.rules_hash()
fw=R/'firmware/am2302';build=fw/'.pio/build/esp32wroom';flasher=json.loads((build/'flasher_args.json').read_text())
out=W/'delivery';out.mkdir(exist_ok=True);images=out/'firmware';images.mkdir(exist_ok=True)
src=out/'firmware-source';src.mkdir(exist_ok=True)
for n in ['src','CMakeLists.txt','platformio.ini','sdkconfig.defaults','configure.py','README.md','hardware.json','test_decode.c']:
 p=fw/n
 if p.is_dir():shutil.copytree(p,src/n,dirs_exist_ok=True)
 else:shutil.copy2(p,src/n)
mapping=[]
for role,name in [('bootloader','bootloader.bin'),('partition-table','partitions.bin'),('app','firmware.bin')]:
 p=build/name;assert p.is_file();shutil.copy2(p,images/name)
 mapping.append(dict(role=role,offset=flasher[role]['offset'],file=name,size=p.stat().st_size,sha256=sha(p)))
ordered=sorted(mapping,key=lambda r:int(r['offset'],16))
assert all(int(a['offset'],16)+a['size']<=int(b['offset'],16) for a,b in zip(ordered,ordered[1:]))
python=W/'build-env/bin/python';esptool=W/'platformio/packages/tool-esptoolpy/esptool.py'
args=[str(python),str(esptool),'--chip','esp32','merge_bin','-o',str(images/'flash-image.bin')]+flasher['write_flash_args']
for row in ordered:args +=[row['offset'],str(images/row['file'])]
p=subprocess.run(args,capture_output=True,text=True);(W/'firmware-merge.log').write_text(p.stdout+p.stderr);assert p.returncode==0,p.stderr
raw=(images/'flash-image.bin').read_bytes()
for row in ordered:
 offset=int(row['offset'],16);assert raw[offset:offset+row['size']]==(images/row['file']).read_bytes()
p=subprocess.run([str(python),str(esptool),'--chip','esp32','image_info',str(images/'firmware.bin')],capture_output=True,text=True);(W/'firmware-image-info.log').write_text(p.stdout+p.stderr);assert p.returncode==0,p.stderr
shutil.copy2(build/'flasher_args.json',images/'idf-flasher-args.json')
pid=report['project_id'];pcb=R/'data'/pid/'pcb_builds'/report['pcb_build_id'];sch=R/'data'/pid/'builds'/report['schematic_build_id']
board=out/'hardware';board.mkdir(exist_ok=True)
for n in ['routed.kicad_pcb','routed.kicad_pro','routed.kicad_dru','fp-lib-table','drc_report.json','layout_routed.json','copper_report.json','router_command.json']:
 assert (pcb/n).is_file(),n;shutil.copy2(pcb/n,board/n)
# Keep review bundle as generated by the MCP, including local library references.
bundle=next(pcb.glob('*review*.zip'));shutil.copy2(bundle,out/bundle.name)
schematic=board/'schematic';schematic.mkdir(exist_ok=True)
for n in ['led.kicad_sch','led.kicad_pro','sym-lib-table','fp-lib-table','actual.xml','erc.json','verify.json']:
 assert (sch/n).is_file(),n;shutil.copy2(sch/n,schematic/n)
shutil.copy2(sch/'review_bundle.zip',out/'schematic_review_bundle.zip')
for n in ['bom-r'+str(report['revision'])+'.csv','bom-r'+str(report['revision'])+'.json']:
 shutil.copy2(R/'data'/pid/'exports'/n,board/n)
for n in ['report.json','交付报告.md','interface-regressions.log','parser-test.log','firmware-build.log','runtime-observation.json','board.pdf','board-preview.png']:
 shutil.copy2(W/n,out/n)
manifest=dict(project_id=pid,revision=report['revision'],schematic_build_id=report['schematic_build_id'],pcb_build_id=report['pcb_build_id'],mcp_source_evidence_hash=report['source_evidence_hash'],board_sha256=sha(pcb/'routed.kicad_pcb'),firmware_target='ESP32 / 4MB flash / UART0 115200',toolchain='PlatformIO 6.1.18 / espressif32 6.12.0 / ESP-IDF 5.5.0 / GCC 14.2.0',flash_settings=flasher['flash_settings'],flash_images=ordered,merged_image_offset='0x0',merged_image_sha256=sha(images/'flash-image.bin'),physical_verified=False,manufacturing_approved=False,source_files={str(p.relative_to(src)):sha(p) for p in sorted(src.rglob('*')) if p.is_file()})
(out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2))
archive=W/'esp32-am2302-interface-and-firmware.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
 for p in sorted(out.rglob('*')):
  if p.is_file():z.write(p,str(p.relative_to(out)))
result=dict(archive=str(archive),sha256=sha(archive),manifest=manifest,merged_images_verified_byte_for_byte=True,real_device_written=False)
(W/'firmware-release.json').write_text(json.dumps(result,ensure_ascii=False,indent=2));print(json.dumps({k:v for k,v in result.items() if k!='manifest'},indent=2))
